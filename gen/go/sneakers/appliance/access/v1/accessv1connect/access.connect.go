// The local API of sneakers-accessd on /run/sneakers/access.sock. The peer
// uid (SO_PEERCRED) is the caller's identity, never a field of a request:
// root is the console (and firstboot), and gets every method here; an
// admin uid is a closed-shell login, acting as that admin with that
// admin's role, and gets only the methods the shell needs; the osadmin uid
// gets BindingService here and the :8443 API of
// sneakers.appliance.osadmin.v1, where every call carries the signed-in
