	// ListKeys lists an admin's login keys; empty admin means the caller.
	ListKeys(context.Context, *connect.Request[v1.ListKeysRequest]) (*connect.Response[v1.ListKeysResponse], error)
	// AddKey is no longer served: the box issues SSH keys on :8443 and never
	// takes one an admin brings.
	//
	// Deprecated: do not use.
	AddKey(context.Context, *connect.Request[v1.AddKeyRequest]) (*connect.Response[v1.AddKeyResponse], error)
	RemoveKey(context.Context, *connect.Request[v1.RemoveKeyRequest]) (*connect.Response[v1.RemoveKeyResponse], error)
